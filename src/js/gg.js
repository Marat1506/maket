// 2. Функция для создания и вывода таблицы частотности
function analyzeCipherText(text) {
    // Удаляем точки, запятые и другие нечисловые разделители, кроме пробелов
    const cleanedText = text.replace(/[.,]/g, '');
    
    // Разбиваем строку на массив чисел
    const numbersArray = cleanedText.split(/\s+/);
    
    // Создаем объект для подсчета частот
    const frequency = {};
    
    // Подсчитываем количество каждого числа
    numbersArray.forEach(num => {
        if (num) { // Проверяем, что элемент не пустой
            frequency[num] = (frequency[num] || 0) + 1;
        }
    });
    
    // Преобразуем объект в массив для сортировки
    const frequencyArray = Object.entries(frequency)
        .map(([number, count]) => ({ number, count }))
        .sort((a, b) => b.count - a.count); // Сортируем по убыванию частоты
    
    // Вычисляем общее количество чисел
    const totalNumbers = numbersArray.length;
    
    // 3. Выводим красивую таблицу в консоль
    console.log('═'.repeat(40));
    console.log('ТАБЛИЦА ЧАСТОТНОСТИ ШИФРООБРАЗОВАНИЙ');
    console.log('═'.repeat(40));
    console.log('Шифрообразование │ Количество │ Частота (%)');
    console.log('─────────────────┼────────────┼────────────');
    
    frequencyArray.forEach(({ number, count }) => {
        const percentage = ((count / totalNumbers) * 100).toFixed(2);
        console.log(`${number.padStart(15)} │ ${count.toString().padStart(10)} │ ${percentage.padStart(10)}%`);
    });
    
    console.log('─'.repeat(40));
    console.log(`Всего элементов: ${totalNumbers}`);
    console.log(`Уникальных шифрообразований: ${frequencyArray.length}`);
    console.log('═'.repeat(40));
    
    return frequencyArray;
}

